`timescale 1ns/1ps

module riscv_pipeline_tb;

    reg clk;
    reg rst_n;

    //--------------------------------------------------
    // DUT
    //--------------------------------------------------

    riscv_pipeline_top DUT(
        .clk(clk),
        .rst_n(rst_n)
    );

    //--------------------------------------------------
    // Clock
    //--------------------------------------------------

    always #5 clk = ~clk;

    //--------------------------------------------------
    // Test Sequence
    //--------------------------------------------------

    initial begin

        $dumpfile("riscv_pipeline.vcd");
        $dumpvars(0, riscv_pipeline_tb);

        clk = 0;
        rst_n = 0;

        //--------------------------------------------------
        // Reset
        //--------------------------------------------------

        #20;
        rst_n = 1;

        //--------------------------------------------------
        // Run Processor
        //--------------------------------------------------

        #500;

        $finish;

    end

endmodule